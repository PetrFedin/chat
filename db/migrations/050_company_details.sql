-- Реквизиты компании.
--
-- При регистрации спрашивали только название и имя владельца. Этого
-- хватает, чтобы начать, и не хватает ни на что дальше: в письмах
-- приглашения нет юридического лица, в договоре с самим сервисом нечего
-- подставить, а сотрудник, зашедший по ссылке, не понимает, та ли это
-- компания, в которую его звали.
--
-- Поля необязательные намеренно: заполнить их можно и потом, из
-- «Компании». Быстрый старт дороже полноты анкеты.
ALTER TABLE organizations
  ADD COLUMN legal_name text,
  ADD COLUMN tax_id text,
  ADD COLUMN address text,
  ADD COLUMN website text,
  ADD COLUMN phone text,
  -- Почтовый домен компании. По нему приглашение на чужой адрес видно
  -- сразу: «ivanov@gmail.com» среди «@granit.ru» — обычно опечатка или
  -- не тот человек.
  ADD COLUMN email_domain text;
