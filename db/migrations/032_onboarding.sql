-- Новый сотрудник попадал в пустую оболочку.
--
-- В первый день человек видит боковую панель с чужими каналами, экран
-- «Сегодня» с нулями и ничего, что объяснило бы, куда здесь смотреть и
-- почему задача — это обещание, а не пункт списка. Продукт со своим
-- устройством знакомил единственным способом: спросите коллегу.
--
-- Хранится ровно один факт — что человек закрыл подсказку. Всё
-- остальное в списке первых шагов выводится из настоящего состояния
-- (есть ли должность, в скольких каналах он состоит, писал ли хоть раз),
-- а не отмечается галочками: «мастер настройки», в котором шаги
-- отмечают сами себя, врёт с первого экрана.
ALTER TABLE workspace_profiles
  ADD COLUMN IF NOT EXISTS onboarding_dismissed_at timestamptz;
