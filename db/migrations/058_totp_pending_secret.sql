-- Начатая настройка не снимает уже включённую защиту.
--
-- «Начать настройку» перезаписывало секрет и обнуляло подтверждение, а
-- включённым второй множитель считается только по подтверждению. Один
-- запрос — и защита снята: пароля он не спрашивал, следа в журнале не
-- оставлял, а на экране незавершённая настройка неотличима от
-- «выключено». Человек, который передумал на полпути, оставался без
-- второго множителя и не знал об этом.
--
-- Новый секрет живёт отдельно, пока его не подтвердят кодом. Старый
-- работает до этой минуты.
ALTER TABLE auth_totp
  ADD COLUMN IF NOT EXISTS pending_secret bytea;
