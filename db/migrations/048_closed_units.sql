-- Закрытое подразделение.
--
-- Оргструктура была целиком открытой: любой сотрудник видел все отделы,
-- их состав, руководителей и планы по местам. Для юридического отдела,
-- службы безопасности или группы, готовящей сделку, это не подходит —
-- там сам список участников и есть тайна.
--
-- Закрытое подразделение видно всем как имя, замок и число людей: за
-- места платит компания, и прятать сам факт существования нельзя. А вот
-- состав, назначение и руководитель — только тем, кто в нём состоит.
ALTER TABLE org_units
  ADD COLUMN visibility text NOT NULL DEFAULT 'open';

ALTER TABLE org_units
  ADD CONSTRAINT org_units_visibility_check CHECK (visibility IN ('open', 'closed'));

-- Читающие пути спрашивают «состою ли я здесь» на каждом показе схемы,
-- поэтому членство ищется по паре «пространство + человек».
CREATE INDEX IF NOT EXISTS org_units_visibility_idx
  ON org_units(workspace_id, visibility);
