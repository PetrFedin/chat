-- Какие пункты протокола уже стали задачами.
--
-- Кнопка «В задачу» ничего о прошлом не помнила: нажали дважды — в
-- списке две одинаковые задачи, и обе настоящие. В жизни это не двойной
-- клик, а два человека, открывших протокол после совещания, или один и
-- тот же человек назавтра.
--
-- Отметка живёт при протоколе, а не при задаче: задачу могут отменить
-- или передать, а пункт всё равно уже зафиксирован — это разные вещи.
-- Ключ — порядковый номер пункта, значение — опознаватель задачи, чтобы
-- повторное нажатие открывало ту же задачу вместо новой.
ALTER TABLE meeting_notes
  ADD COLUMN IF NOT EXISTS committed jsonb NOT NULL DEFAULT '{}'::jsonb;
