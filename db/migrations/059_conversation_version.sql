-- Номер версии у беседы.
--
-- Настройки беседы правились без оглядки на то, что видел правящий:
-- двое, открывшие окно «Настройки канала» одновременно, сохраняли по
-- очереди, и побеждал последний — а первому никто не говорил, что его
-- правку стёрли. У задач эта защита есть с первого дня и сделана
-- образцово: `expectedVersion` обязателен, расхождение отвечает
-- «экран устарел».
--
-- Счётчик начинается с единицы у всех, кто уже заведён: до сих пор
-- беседы не версионировались, и «правильной» прошлой версии у них нет.
ALTER TABLE conversations
  ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
