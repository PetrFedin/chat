-- Комната подразделения.
--
-- Подразделение было строкой в схеме: имя, руководитель, число мест — и
-- ничего, что можно открыть. «Меня добавили в четыре отдела» означало
-- ровно четыре строчки, а не четыре места, где идёт работа: где писать
-- своим и где видеть, что там нового.
--
-- Теперь у каждого подразделения есть своя закрытая беседа, и состав
-- подразделения и состав беседы — одно и то же. Непрочитанное,
-- упоминания, закреплённое и поиск начинают работать в ней сами: это
-- обычная комната, просто её список участников ведёт оргструктура.
ALTER TABLE org_units
  ADD COLUMN conversation_id uuid REFERENCES conversations(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS org_units_conversation_idx
  ON org_units(workspace_id, conversation_id);
