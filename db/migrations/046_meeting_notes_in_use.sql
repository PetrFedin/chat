-- Протокол встречи — по одному на встречу.
--
-- Таблица под протоколы лежала в схеме с самого начала и не читалась
-- ни одной строкой кода: разбор с расшифровкой был только у
-- записанного звонка, а совещание в кабинете зафиксировать было негде.
--
-- Уникальность нужна, чтобы «что решили» не расползлось на два
-- параллельных протокола: это тот же спор, только теперь письменный.

CREATE UNIQUE INDEX meeting_notes_one_per_event
  ON meeting_notes (workspace_id, calendar_event_id)
  WHERE calendar_event_id IS NOT NULL;
