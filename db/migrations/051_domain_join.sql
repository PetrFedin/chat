-- Вход в свою компанию по рабочей почте.
--
-- До сих пор попасть в компанию можно было одним способом: кто-то должен
-- был завести именно тебя и прислать ссылку. Для сорока человек это сорок
-- действий администратора, и каждый новый сотрудник ждёт, пока до него
-- дойдёт очередь.
--
-- Теперь проще: компания объявляет свой почтовый домен и число мест, а
-- человек с адресом на этом домене заводится сам — и получает на почту
-- ссылку-подтверждение. Ссылка та же, что у обычного приглашения: код
-- принятия один, и проверен он один раз.
ALTER TABLE organizations
  -- Сколько человек компания оплачивает. NULL — без ограничения.
  ADD COLUMN seat_limit integer,
  -- Разрешено ли заводиться самому по адресу на домене компании.
  -- Выключено по умолчанию: домен мог быть вписан просто для порядка.
  ADD COLUMN domain_join boolean NOT NULL DEFAULT false;

ALTER TABLE organizations
  ADD CONSTRAINT organizations_seat_limit_check CHECK (seat_limit IS NULL OR seat_limit > 0);

-- Поиск компании по домену — на каждом самостоятельном заведении.
CREATE INDEX IF NOT EXISTS organizations_email_domain_idx
  ON organizations(lower(email_domain)) WHERE email_domain IS NOT NULL;
