-- У компании ровно один владелец.
--
-- Это правило держалось на коде, и код его не удержал: два одновременных
-- «передать владение» проходили оба, и в компании оказывалось два хозяина,
-- а инициатор оставался администратором. Проверка «я всё ещё владелец»
-- читала строку без блокировки и принимала решение по устаревшему снимку.
--
-- Уникальный частичный индекс делает второе такое решение невозможным:
-- вторая транзакция упадёт на ограничении, а не разойдётся с первой.

-- На случай уже разошедшихся данных: оставляем владельцем самого раннего,
-- остальных переводим в администраторы — роль, которую передача владения
-- и так оставляет прежнему хозяину.
UPDATE memberships m
   SET role = 'admin'
 WHERE m.role = 'owner'
   AND m.ctid <> (SELECT m2.ctid FROM memberships m2
                   WHERE m2.workspace_id = m.workspace_id AND m2.role = 'owner'
                   ORDER BY m2.created_at, m2.user_id LIMIT 1);

CREATE UNIQUE INDEX memberships_single_owner_uq
    ON memberships (workspace_id)
 WHERE role = 'owner';
