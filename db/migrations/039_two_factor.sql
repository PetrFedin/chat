-- Второй множитель входа.
--
-- Пароль был единственным, что отделяло чужого человека от переписки
-- компании, сейфа с паролями и журнала действий. Подсмотренный или
-- повторно использованный на стороннем сайте, он открывал пространство
-- целиком, и заметить это было нечем.
--
-- Привязка к человеку, а не к участию в пространстве: телефон у
-- человека один, и заводить по второму множителю на каждую компанию,
-- где он работает, — это способ добиться, чтобы его не включил никто.

CREATE TABLE auth_totp (
  user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  -- Секрет лежит запечатанным тем же ключом, что и сейф паролей:
  -- украденный дамп базы не должен давать возможность выпускать коды.
  secret bytea NOT NULL,
  -- Пока не подтверждён — не действует. Иначе человек включает второй
  -- множитель, ошибается при настройке приложения и запирает себя
  -- снаружи собственного пространства.
  confirmed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz,
  -- Номер последнего использованного окна: один и тот же код нельзя
  -- предъявить дважды, иначе подсмотренный через плечо код работает
  -- все тридцать секунд, а не до первого входа.
  last_counter bigint
);

-- Запасные коды: телефон теряется и ломается. Без них второй множитель
-- превращается в запертую дверь без ключа, и для владельца компании
-- выхода не остаётся вовсе.
CREATE TABLE auth_recovery_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- Хранится отпечаток, а не код: список запасных кодов в открытом виде
  -- в базе — это тот же пароль, только записанный десять раз.
  code_hash text NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, code_hash)
);

CREATE INDEX auth_recovery_codes_unused ON auth_recovery_codes (user_id) WHERE used_at IS NULL;
