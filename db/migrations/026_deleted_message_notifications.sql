-- «Удалить у всех» должно значить у всех.
--
-- Тело уведомления — снимок сообщения на момент отправки, и это правильно:
-- центру внимания незачем ходить в переписку за каждой строкой. Но снимок
-- переживал само сообщение: человек удалял написанное, из чата оно
-- исчезало, а полный текст оставался в колокольчике у всех, кому пришёл, —
-- навсегда и без единого способа его убрать.
--
-- Дальше этого не случится: удаление гасит тело в той же транзакции, а
-- чтение прячет старые снимки. Здесь мы убираем то, что уже накоплено, —
-- прятать на чтении и хранить в базе значит держать обещание наполовину.

UPDATE notifications n
   SET body = 'Сообщение удалено',
       updated_at = now()
  FROM messages m
 WHERE m.workspace_id = n.workspace_id
   AND m.id = n.message_id
   AND m.deleted_at IS NOT NULL
   AND n.body IS DISTINCT FROM 'Сообщение удалено';
